-- V1 shipped in release 0.3.0 and is applied in every environment. Never edit an applied migration:
-- Flyway validates checksums on startup and the deploy fails. Add V2__... instead.
CREATE TABLE course (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(60)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    level       VARCHAR(20)  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE lesson (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT       NOT NULL,
    position    INT          NOT NULL,
    title       VARCHAR(200) NOT NULL
);

CREATE TABLE quiz_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id    BIGINT        NOT NULL,
    stem         VARCHAR(1000) NOT NULL,
    answer_index INT           NOT NULL,
    explanation  VARCHAR(2000) NOT NULL
);

CREATE TABLE quiz_item_option (
    quiz_item_id BIGINT       NOT NULL,
    option_order INT          NOT NULL,
    option_text  VARCHAR(500) NOT NULL,
    PRIMARY KEY (quiz_item_id, option_order)
);

CREATE TABLE quiz_attempt (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_item_id  BIGINT      NOT NULL,
    learner_id    VARCHAR(64) NOT NULL,
    chosen_index  INT         NOT NULL,
    correct       BOOLEAN     NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
