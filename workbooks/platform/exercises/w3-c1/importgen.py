#!/usr/bin/env python3
"""tsl-import-gen: draft Terraform import blocks from a Cloud Asset Inventory export.

Reads an export (inventory/cai-export.json), the import IDs Terraform already manages
(inventory/state-ids.json: address -> import ID, from `terraform state list` + `terraform show`), and a
project number -> project ID map. Writes imports/<owner>/imports.tf and imports/report.json.

Usage: python importgen.py [--inventory inventory] [--out imports]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HEADER = "# Generated by tsl-import-gen from Cloud Asset Inventory. Review before merging.\n"
DEFAULT_OWNER = "platform"
MANAGED_DOMAINS = ("cloudservices.gserviceaccount.com", "developer.gserviceaccount.com", "appspot.gserviceaccount.com")


# ----------------------------------------------------------------- helpers
def ident(raw: str) -> str:
    """TODO: a valid, stable Terraform identifier (README "Identifiers")."""
    return raw.replace("-", "_")


def owner_dir(raw: str | None) -> str:
    """TODO: directory name for an owner label; missing owner -> DEFAULT_OWNER."""
    return raw or DEFAULT_OWNER


def google_managed_email(email: str) -> bool:
    """TODO: True for Google-managed service accounts and service agents (README "Skip rules")."""
    return False


def project_of(asset: dict, projects: dict) -> str | None:
    m = re.search(r"/projects/([^/]+)", asset["name"])
    if m and not m.group(1).isdigit():
        return m.group(1)
    parent = (asset.get("resource") or {}).get("parent", "")
    m = re.search(r"/projects/(\d+)$", parent)
    return projects.get(m.group(1)) if m else None


def last(url: str) -> str:
    return url.rstrip("/").rsplit("/", 1)[-1]


# ----------------------------------------------------------------- mappers: asset -> candidates
def map_asset(asset: dict, projects: dict) -> tuple[list[dict], list[dict]]:
    """Return (candidates, skipped). A candidate: type, name (for the identifier), id, owner, key."""
    t = asset["assetType"]
    data = (asset.get("resource") or {}).get("data") or {}
    labels = data.get("labels") or {}
    p = project_of(asset, projects)
    if t == "compute.googleapis.com/Network":
        return [{"type": "google_compute_network", "name": data["name"], "owner": labels.get("owner"),
                 "id": f"projects/{p}/global/networks/{data['name']}", "network": data["name"]}], []
    # TODO: Subnetwork, Bucket, ServiceAccount, SQL Instance, project IAM bindings (README "Mappings")
    if t == "compute.googleapis.com/Firewall":
        return [{"type": "google_compute_firewall", "name": data["name"], "owner": labels.get("owner"),
                 "id": f"projects/{p}/global/firewalls/{data['name']}"}], []
    return [], [{"name": asset["name"], "reason": f"unsupported asset type {t}", "unsupported": True}]


# ----------------------------------------------------------------- generate
def generate(assets: list[dict], state_ids: dict, projects: dict) -> dict:
    managed = set(state_ids.values())
    cands, skipped, unsupported, already = [], [], [], []
    for a in assets:
        c, s = map_asset(a, projects)
        cands += c
        for x in s:
            (unsupported if x.pop("unsupported", False) else skipped).append(x)
    # TODO: subnetworks inherit their network's owner; skip IDs Terraform already manages (report them)
    for c in cands:
        c["owner"] = owner_dir(c["owner"])
    todo = cands
    files: dict[str, list[tuple[str, str, str]]] = {}
    used: dict[tuple[str, str], set] = {}
    for c in sorted(todo, key=lambda c: (c["owner"], c["type"], c["id"])):
        base = ident(c["name"])
        taken = used.setdefault((c["owner"], c["type"]), set())
        name = base  # TODO: collisions within one file and type get _2, _3 ... (stable)
        taken.add(name)
        files.setdefault(c["owner"], []).append((c["type"], name, c["id"]))
    rendered = {}
    for owner, blocks in sorted(files.items()):
        parts = [HEADER]
        for typ, name, iid in sorted(blocks):
            parts.append(f'\nimport {{\n  to = {typ}.{name}\n  id = "{iid}"\n}}\n')
        rendered[f"{owner}/imports.tf"] = "".join(parts)
    report = {"skipped": sorted(skipped, key=lambda x: x["name"]),
              "unsupported": sorted(unsupported, key=lambda x: x["name"]),
              "already_managed": sorted(already)}
    return {"files": rendered, "report": report}


def main(argv=None) -> int:
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description="draft import blocks from a CAI export")
    ap.add_argument("--inventory", default=str(here / "inventory"))
    ap.add_argument("--out", default=str(here / "imports"))
    a = ap.parse_args(argv)
    inv = Path(a.inventory)
    try:
        assets = json.loads((inv / "cai-export.json").read_text())["assets"]
        state = json.loads((inv / "state-ids.json").read_text())
        projects = json.loads((inv / "projects.json").read_text())
    except (OSError, ValueError, KeyError) as e:
        print(f"importgen: {e}", file=sys.stderr)
        return 2
    res = generate(assets, state, projects)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for rel, text in res["files"].items():
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        (out / rel).write_text(text)
    (out / "report.json").write_text(json.dumps(res["report"], indent=2) + "\n")
    n = sum(t.count("import {") for t in res["files"].values())
    print(f"wrote {n} import blocks in {len(res['files'])} file(s) under {out}; "
          f"{len(res['report']['skipped'])} skipped, {len(res['report']['unsupported'])} unsupported, "
          f"{len(res['report']['already_managed'])} already managed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
