#!/usr/bin/env bash
# Shared grader for TypeScript/jest exercises. Copies the exercise to a temp dir (the learner's
# folder is never written to), adds .grading/tests as tests/__hidden__, runs jest on visible +
# hidden tests under a timeout and prints one line per test, then the summary line:
#   GRADE_TESTS {"passed": N, "total": M}
# Usage: grade-jest.sh <ex_dir> <expected_total> [timeout_seconds]
# Exit 0 whenever the tests ran; 2 when the harness itself broke.
set -u
ex_dir="${1:?ex_dir}"; expected="${2:-0}"; secs="${3:-240}"
env_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
harness_fail() { echo "HARNESS ERROR: ${1}" >&2; echo "HARNESS ERROR: ${1}"; exit 2; }
command -v node >/dev/null 2>&1 || harness_fail "node not found. Run tools/doctor.sh connect."
bash "${env_dir}/ensure-node.sh" >&2 || harness_fail "could not install the shared toolchain (see above)"

tmp="$(mktemp -d "${TMPDIR:-/tmp}/grade-connect.XXXXXX")"
trap 'rm -rf "${tmp}"' EXIT
work="${tmp}/$(basename "${ex_dir}")"
mkdir -p "${work}"
(cd "${ex_dir}" && tar --exclude ./node_modules --exclude ./coverage --exclude ./cdk.out --exclude ./incident \
  --exclude ./.grading/solution --exclude ./.grading/reference.md --exclude ./.grading/rubric.md -cf - .) | (cd "${work}" && tar -xf -) \
  || harness_fail "could not copy the exercise to a temp dir"
ln -s "${env_dir}/node_modules" "${work}/node_modules"
# troubleshooting bundles generated by make setup are inputs to some hidden tests: regenerate in the copy
if [ -f "${work}/Makefile" ] && grep -q '^bundle:' "${work}/Makefile"; then
  make -s -C "${work}" bundle >/dev/null 2>&1 || true
fi
mkdir -p "${work}/tests/__hidden__"
if ls "${ex_dir}/.grading/tests/"* >/dev/null 2>&1; then
  cp -R "${ex_dir}/.grading/tests/." "${work}/tests/__hidden__/"
fi
rm -rf "${work}/.grading"

if command -v timeout >/dev/null 2>&1; then TO=(timeout "${secs}"); elif command -v gtimeout >/dev/null 2>&1; then TO=(gtimeout "${secs}"); else TO=(perl -e 'alarm shift; exec @ARGV' "${secs}"); fi
(cd "${work}" && CONNECT_GRADING=1 "${TO[@]}" "${env_dir}/node_modules/.bin/jest" --ci --json --outputFile="${tmp}/jest.json" --forceExit >"${tmp}/jest.log" 2>&1)
rc=$?
if [ ! -s "${tmp}/jest.json" ]; then
  tail -n 40 "${tmp}/jest.log"
  if [ "${rc}" -eq 124 ] || [ "${rc}" -eq 142 ]; then
    echo "jest exceeded ${secs}s and was stopped (a hang counts as failure)"
    echo "GRADE_TESTS {\"passed\": 0, \"total\": ${expected}}"
    exit 0
  fi
  harness_fail "jest produced no report (exit ${rc})"
fi
node "${env_dir}/jest-summary.js" "${tmp}/jest.json" "${expected}"
