"""Client for catalog-service's inventory endpoints, plus the local fake used by demos and tests.

Production uses an httpx-based client with the same two methods. Do not edit this file: the fix
belongs in inventory_tool.py.

Endpoints:
  GET  /inventory/{sku}?store_id=...     one SKU at one store          -> get_stock()
  POST /inventory/lookup                 up to 50 (sku, store) pairs   -> batch_stock()
       (shipped by the catalog team in 2026.08; same p50 as a single GET)
"""

from __future__ import annotations

import asyncio
from typing import Callable, Iterable, Protocol

BATCH_MAX = 50


class CatalogError(Exception):
    pass


class CatalogTimeout(CatalogError):
    pass


class CatalogClient(Protocol):
    async def get_stock(self, sku: str, store_id: str, timeout: float) -> int: ...

    async def batch_stock(self, items: list[tuple[str, str]], timeout: float) -> dict[tuple[str, str], int]: ...


def _stock(sku: str, store_id: str) -> int:
    return (sum(map(ord, sku)) + int(store_id)) % 7


class FakeCatalog:
    """In-memory catalog with configurable latency. Records how it was called."""

    def __init__(
        self,
        latency_s: float = 0.05,
        batch_latency_s: float | None = None,
        fail_batch: Callable[[list[tuple[str, str]]], bool] | None = None,
    ) -> None:
        self.latency_s = latency_s
        self.batch_latency_s = latency_s if batch_latency_s is None else batch_latency_s
        self.fail_batch = fail_batch
        self.single_calls = 0
        self.batch_calls = 0
        self.batch_sizes: list[int] = []
        self.in_flight = 0
        self.max_in_flight = 0
        self.timeouts_seen: list[float] = []

    @staticmethod
    def truth(sku: str, store_id: str) -> int:
        return _stock(sku, store_id)

    async def _wait(self, latency: float, timeout: float) -> None:
        self.timeouts_seen.append(timeout)
        self.in_flight += 1
        self.max_in_flight = max(self.max_in_flight, self.in_flight)
        try:
            if latency > timeout:
                await asyncio.sleep(max(0.0, timeout))
                raise CatalogTimeout(f"catalog did not answer within {timeout:.2f}s")
            await asyncio.sleep(latency)
        finally:
            self.in_flight -= 1

    async def get_stock(self, sku: str, store_id: str, timeout: float) -> int:
        self.single_calls += 1
        await self._wait(self.latency_s, timeout)
        return _stock(sku, store_id)

    async def batch_stock(self, items: list[tuple[str, str]], timeout: float) -> dict[tuple[str, str], int]:
        items = list(items)
        if len(items) > BATCH_MAX:
            raise CatalogError(f"batch of {len(items)} exceeds {BATCH_MAX}")
        self.batch_calls += 1
        self.batch_sizes.append(len(items))
        await self._wait(self.batch_latency_s, timeout)
        if self.fail_batch and self.fail_batch(items):
            raise CatalogError("catalog returned HTTP 503")
        return {(s, st): _stock(s, st) for s, st in items}


def pairs(skus: Iterable[str], stores: Iterable[str]) -> list[tuple[str, str]]:
    return [(s, st) for s in skus for st in stores]
